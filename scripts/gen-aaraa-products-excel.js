function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/**
 * Build a row.
 * @param {number}  catId
 * @param {string}  name
 * @param {string}  hsn
 * @param {number}  taxPct  5 or 18
 */
function row(catId, name, hsn, taxPct) {
  const taxId = taxPct === 18 ? TAX_18_ID : TAX_5_ID;
  return {
    id:          "",
    categoryId:  catId,
    name:        name.trim(),
    slug:        slugify(name.trim()),
    brandId:     BRAND_ID,
    description: "",
    hsnCode:     String(hsn).trim(),
    taxPercent:  taxPct,
    taxId:       taxId,
  };
}

